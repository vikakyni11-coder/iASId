def quote_of_the_day(seed=None):
    """Цитата дня: детерминирована для одного дня (или переданного seed)."""
    if seed is None:
        seed = int(time.time()) // 86400
    return random.Random(seed).choice(QUOTES)


def random_quote(seed=None):
    """Совсем случайная цитата."""
    return random.Random(seed).choice(QUOTES)


def motivational_poster(topic):
    """Генерирует постер-надпись по заданной теме."""
    templates = [
        f"«{topic}» — это не просто слова. Это ровно такие же слова, "
        "как и все остальные.",
        f"Всё возможно, если слово «{topic}» не читать как «завтра».",
        f"Только вперёд! Особенно если «{topic}» где-то там, впереди.",
        f"«{topic}» ждёт тебя. Наверное. Где-то.",
    ]
    return random.Random(hash(topic)).choice(templates)
