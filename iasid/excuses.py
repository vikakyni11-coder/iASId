def random_excuse(seed=None):
    """Возвращает случайную отмазку."""
    return random.Random(seed).choice(EXCUSES)


def excuse_of_the_day(day_key=None):
    """Возвращает отмазку дня — стабильную в течение суток.

    day_key: строка вида 'YYYY-MM-DD' или любой другой ключ.
    """
    if day_key is None:
        day_key = time.strftime("%Y-%m-%d")
    return random.Random(day_key).choice(EXCUSES)


def excuses_for_context(context, seed=None, count=3):
    """Возвращает список отмазок для конкретного контекста."""
    pool = CONTEXT_EXCUSES.get(context, EXCUSES)
    rng = random.Random(seed)
    return [rng.choice(pool) for _ in range(count)]


def all_contexts():
    """Возвращает список доступных контекстов."""
    return sorted(CONTEXT_EXCUSES)
