def signs():
    """Список знаков зодиака."""
    return sorted(ZODIAC)


def horoscope(sign, seed=None):
    """Гороскоп для знака. Без seed — стабилен в течение дня."""
    sign = sign.lower().strip()
    if sign not in ZODIAC:
        raise ValueError(
            f"неизвестный знак: {sign}. Доступно: {', '.join(signs())}"
        )
    if seed is None:
        seed = int(time.time()) // 86400
    rng = random.Random(seed)
    template = rng.choice(TEMPLATES)
    rating = rng.randint(1, 10)
    return f"{template.format(sign=sign.capitalize())} Рейтинг дня: {rating}/10."


def compatibility(sign_a, sign_b, seed=None):
    """Совместимость двух знаков: оценка 1-100 и вердикт."""
    sign_a = sign_a.lower().strip()
    sign_b = sign_b.lower().strip()
    if sign_a not in ZODIAC or sign_b not in ZODIAC:
        raise ValueError("оба знака должны быть из списка: " + ", ".join(signs()))
    if seed is None:
        seed = int(time.time()) // 86400 + (hash(sign_a) + hash(sign_b)) % 31
    score = random.Random(seed).randint(1, 100)
    if score > 75:
        verdict = "идеальная пара, звёзды уже заказали торт"
    elif score > 45:
        verdict = "совместимы, но один из вас скрывает что-то важное"
    else:
        verdict = "лучше держаться на расстоянии полутора орбит"
    return {"signs": (sign_a, sign_b), "score": score, "verdict": verdict}


def fortune(seed=None):
    """Случайное предсказание судьбы."""
    if seed is None:
        seed = int(time.time()) // 86400
    return random.Random(seed).choice(FORTUNES)
